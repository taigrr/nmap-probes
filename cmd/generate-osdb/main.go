// Command generate-osdb converts nmap-os-db to a Go source file
// containing the raw file data as a string constant.
//
// Usage:
//
//	go run ./cmd/generate-osdb/ -input /path/to/nmap-os-db -o osdb_generated.go
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"time"
)

func main() {
	input := flag.String("input", "", "Path to nmap-os-db file")
	output := flag.String("o", "osdb_generated.go", "Output file path")
	flag.Parse()

	if *input == "" {
		log.Fatal("--input is required (path to nmap-os-db)")
	}

	data, err := os.ReadFile(*input)
	if err != nil {
		log.Fatalf("reading input: %v", err)
	}

	log.Printf("Read %d bytes from %s", len(data), *input)

	out, err := os.Create(*output)
	if err != nil {
		log.Fatalf("creating output: %v", err)
	}
	defer out.Close()

	fmt.Fprintf(out, "// Code generated by generate-osdb; DO NOT EDIT.\n")
	fmt.Fprintf(out, "// Source: nmap-os-db\n")
	fmt.Fprintf(out, "// Generated: %s\n\n", time.Now().UTC().Format(time.RFC3339))
	fmt.Fprintf(out, "package nmapprobes\n\n")
	fmt.Fprintf(out, "// embeddedOSDB contains the raw nmap-os-db file content.\n")
	fmt.Fprintf(out, "var embeddedOSDB = %q\n", string(data))

	log.Printf("Generated %s", *output)
}
