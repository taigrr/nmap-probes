// Command generate-probes converts nmap-service-probes to a Go source file
// containing the raw file data as a string constant.
//
// Usage:
//
//	go run ./cmd/generate-probes/ -input /path/to/nmap-service-probes -o probes_generated.go
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"time"
)

func main() {
	input := flag.String("input", "", "Path to nmap-service-probes file")
	output := flag.String("o", "probes_generated.go", "Output file path")
	flag.Parse()

	if *input == "" {
		log.Fatal("--input is required (path to nmap-service-probes)")
	}

	data, err := os.ReadFile(*input)
	if err != nil {
		log.Fatalf("reading input: %v", err)
	}

	log.Printf("Read %d bytes from %s", len(data), *input)

	out, err := os.Create(*output)
	if err != nil {
		log.Fatalf("creating output: %v", err)
	}
	defer out.Close()

	fmt.Fprintf(out, "// Code generated by generate-probes; DO NOT EDIT.\n")
	fmt.Fprintf(out, "// Source: nmap-service-probes\n")
	fmt.Fprintf(out, "// Generated: %s\n\n", time.Now().UTC().Format(time.RFC3339))
	fmt.Fprintf(out, "package nmapprobes\n\n")
	fmt.Fprintf(out, "// embeddedServiceProbes contains the raw nmap-service-probes file content.\n")
	fmt.Fprintf(out, "var embeddedServiceProbes = %q\n", string(data))

	log.Printf("Generated %s", *output)
}
